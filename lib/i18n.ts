export type I18nKey = keyof typeof ru;
/** t("limits.of", { x: "88 000" }) → «из 88 000» */
export const t = (key: I18nKey, vars?: Record<string, string | number>): string =>
  vars ? ru[key].replace(/\{(\w+)\}/g, (m, k: string) => (k in vars ? String(vars[k]) : m)) : ru[key];
